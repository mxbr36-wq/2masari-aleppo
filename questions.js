function isValid(question) {
  const dimensions = Object.keys(question.options || {});
  return Boolean(question.text && question.icon && question.topic)
    && dimensions.length === 4
    && dimensions.every(dimension => DIMENSION_KEYS.includes(dimension) && question.options[dimension]);
}

// A bad row is skipped (and logged) instead of taking the whole site down.
const validQuestions = QUESTIONS.filter((question, index) => {
  const valid = isValid(question);
  if (!valid) console.error(`questions.js: question #${index} is invalid and was skipped`, question.text);
  return valid;
});

// The shape app.js reads: [scenario, [[answer, dimension] x 4], icon, topic]
export const QUESTION_BANK = validQuestions.map(({ text, options, icon, topic }) => [
  text,
  Object.entries(options).map(([dimension, answer]) => [answer, dimension]),
  icon,
  topic
]);

if (new Set(QUESTION_BANK.map(question => question[3])).size < MIN_TOPICS) {
  throw new Error(`QUESTION_BANK needs at least ${MIN_TOPICS} distinct topics`);
}
